#!/usr/bin/env python3
"""Generates the Walletka app icon sources from one geometry definition.

Outputs (paths relative to the repository root):
  design/app-icon.svg, design/app-icon-dark.svg, design/app-icon-tinted.svg  -- 1024x1024 iOS masters
  androidApp/src/main/res/drawable/ic_launcher_{background,foreground,monochrome}.xml -- adaptive icon layers

Render the iOS PNGs afterwards with `design/render_icons.sh`.

The mark: a wallet card (with a small QR code and name lines) in front of a second card, framed by scanner
viewfinder brackets, on the app's indigo -> teal gradient.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

INDIGO = "#5856D6"
TEAL = "#30B0C7"

# Geometry, centred on (0, 0) in 1024-unit icon space.
BRACKET_HALF = 300      # half the side of the viewfinder square
BRACKET_ARM = 120
BRACKET_RADIUS = 44
BRACKET_STROKE = 46
CARD_W, CARD_H, CARD_R = 476, 300, 46
CARD_ROTATION = -8
BACK_CARD_ROTATION = 6
BACK_CARD_OFFSET = (26, -44)


def rr(x, y, w, h, r):
    """Rounded rectangle as path data (absolute commands, understood by SVG and VectorDrawable)."""
    return (f"M{x + r},{y} H{x + w - r} A{r},{r} 0 0 1 {x + w},{y + r} V{y + h - r} "
            f"A{r},{r} 0 0 1 {x + w - r},{y + h} H{x + r} A{r},{r} 0 0 1 {x},{y + h - r} "
            f"V{y + r} A{r},{r} 0 0 1 {x + r},{y} Z")


def brackets():
    h, a, r = BRACKET_HALF, BRACKET_ARM, BRACKET_RADIUS
    parts = []
    for sx, sy in ((-1, -1), (1, -1), (1, 1), (-1, 1)):
        # Arm along y, rounded corner, arm along x.
        sweep = 1 if sx * sy > 0 else 0
        parts.append(f"M{sx * h},{sy * (h - a)} V{sy * (h - r)} "
                     f"A{r},{r} 0 0 {sweep} {sx * (h - r)},{sy * h} H{sx * (h - a)}")
    return " ".join(parts)


CARD = rr(-CARD_W / 2, -CARD_H / 2, CARD_W, CARD_H, CARD_R)
LINES = [rr(-196, -104, 176, 36, 18), rr(-196, -48, 112, 36, 18), rr(-196, 64, 84, 36, 18)]

# A small QR code: three finder patterns plus a few data modules, 150 units square on the card's right.
QX, QY, QS = 46, -76, 152
FINDER, RING, DOT = 56, 13, 18


def finder(x, y):
    ring = rr(x, y, FINDER, FINDER, 13) + " " + rr(x + RING, y + RING, FINDER - 2 * RING, FINDER - 2 * RING, 6)
    o = (FINDER - DOT) / 2
    return ring, rr(x + o, y + o, DOT, DOT, 5)


FINDERS = [finder(QX, QY), finder(QX + QS - FINDER, QY), finder(QX, QY + QS - FINDER)]
M = 18
MODULES = [rr(QX + dx, QY + dy, M, M, 5) for dx, dy in (
    (96, 96), (134, 96), (115, 115), (96, 134), (134, 134),  # bottom-right block
    (67, 6), (67, 34), (6, 67), (34, 67), (67, 67),          # modules between the finders
)]


def qr_shapes():
    """Every QR and text shape as separate path data (rings use even-odd)."""
    rings = [ring for ring, _ in FINDERS]
    dots = [dot for _, dot in FINDERS] + MODULES
    return rings, dots


# ---------------------------------------------------------------------------------------------------- SVG

def svg(theme):
    rings, dots = qr_shapes()
    if theme == "light":
        defs = f"""<linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="{INDIGO}"/><stop offset="1" stop-color="{TEAL}"/>
    </linearGradient>"""
        background = '<rect width="1024" height="1024" fill="url(#bg)"/>'
        bracket, back, back_opacity, card, qr, lines = "#FFFFFF", "#FFFFFF", 0.38, "#FFFFFF", INDIGO, TEAL
    elif theme == "dark":
        defs = f"""<linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#1B1A3A"/><stop offset="1" stop-color="#0A2329"/>
    </linearGradient>
    <linearGradient id="card" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#5E5CE6"/><stop offset="1" stop-color="#40C8E0"/>
    </linearGradient>"""
        background = '<rect width="1024" height="1024" fill="url(#bg)"/>'
        bracket, back, back_opacity, card, qr, lines = "#40C8E0", "#FFFFFF", 0.22, "url(#card)", "#FFFFFF", "#FFFFFF"
    else:  # tinted: grayscale, the system applies the user's tint
        defs = ""
        background = '<rect width="1024" height="1024" fill="#000000"/>'
        bracket, back, back_opacity, card, qr, lines = "#C8C8C8", "#FFFFFF", 0.3, "#F2F2F2", "#3A3A3A", "#7A7A7A"
    line_opacity = ' opacity="0.85"' if theme == "dark" else ""
    bx, by = BACK_CARD_OFFSET
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <!-- Generated by design/generate_icons.py; edit the script, not this file. -->
  <defs>
    {defs}
  </defs>
  {background}
  <g transform="translate(512 512)">
    <path d="{brackets()}" fill="none" stroke="{bracket}" stroke-width="{BRACKET_STROKE}" stroke-linecap="round" stroke-linejoin="round"/>
    <g transform="translate({bx} {by}) rotate({BACK_CARD_ROTATION})">
      <path d="{CARD}" fill="{back}" opacity="{back_opacity}"/>
    </g>
    <g transform="rotate({CARD_ROTATION})">
      <path d="{CARD}" fill="{card}"/>
      <path d="{' '.join(LINES)}" fill="{lines}"{line_opacity}/>
      <path d="{' '.join(rings)}" fill="{qr}" fill-rule="evenodd"/>
      <path d="{' '.join(dots)}" fill="{qr}"/>
    </g>
  </g>
</svg>
"""


# ------------------------------------------------------------------------------------------- VectorDrawable

# Adaptive icons are 108dp; the mark must stay inside the 66dp safe circle (brackets' corners included).
VD_SCALE = 0.072
VD_HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by design/generate_icons.py; edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
"""


def vd_mark(inner):
    return f"""    <group
        android:translateX="54"
        android:translateY="54"
        android:scaleX="{VD_SCALE}"
        android:scaleY="{VD_SCALE}">
{inner}    </group>
"""


def vd_brackets(color):
    return f"""        <path
            android:pathData="{brackets()}"
            android:strokeColor="{color}"
            android:strokeWidth="{BRACKET_STROKE}"
            android:strokeLineCap="round"
            android:strokeLineJoin="round" />
"""


def vd_background():
    return VD_HEADER + f"""    <path android:pathData="M0,0 H108 V108 H0 Z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="0"
                android:startY="0"
                android:endX="108"
                android:endY="108"
                android:startColor="#FF{INDIGO[1:]}"
                android:endColor="#FF{TEAL[1:]}" />
        </aapt:attr>
    </path>
</vector>
"""


def vd_foreground():
    rings, dots = qr_shapes()
    bx, by = BACK_CARD_OFFSET
    inner = vd_brackets("#FFFFFFFF") + f"""        <group
            android:translateX="{bx}"
            android:translateY="{by}"
            android:rotation="{BACK_CARD_ROTATION}">
            <path
                android:pathData="{CARD}"
                android:fillColor="#61FFFFFF" />
        </group>
        <group android:rotation="{CARD_ROTATION}">
            <path
                android:pathData="{CARD}"
                android:fillColor="#FFFFFFFF" />
            <path
                android:pathData="{' '.join(LINES)}"
                android:fillColor="#FF{TEAL[1:]}" />
            <path
                android:pathData="{' '.join(rings)}"
                android:fillColor="#FF{INDIGO[1:]}"
                android:fillType="evenOdd" />
            <path
                android:pathData="{' '.join(dots)}"
                android:fillColor="#FF{INDIGO[1:]}" />
        </group>
"""
    return VD_HEADER + vd_mark(inner) + "</vector>\n"


def vd_monochrome():
    """Themed-icon layer: one colour, the card's contents knocked out of it."""
    rings, dots = qr_shapes()
    knocked = " ".join([CARD] + LINES + rings + dots)
    inner = vd_brackets("#FFFFFFFF") + f"""        <group android:rotation="{CARD_ROTATION}">
            <path
                android:pathData="{knocked}"
                android:fillColor="#FFFFFFFF"
                android:fillType="evenOdd" />
        </group>
"""
    return VD_HEADER + vd_mark(inner) + "</vector>\n"


def main():
    design = ROOT / "design"
    (design / "app-icon.svg").write_text(svg("light"))
    (design / "app-icon-dark.svg").write_text(svg("dark"))
    (design / "app-icon-tinted.svg").write_text(svg("tinted"))
    res = ROOT / "androidApp/src/main/res/drawable"
    (res / "ic_launcher_background.xml").write_text(vd_background())
    (res / "ic_launcher_foreground.xml").write_text(vd_foreground())
    (res / "ic_launcher_monochrome.xml").write_text(vd_monochrome())


if __name__ == "__main__":
    main()
